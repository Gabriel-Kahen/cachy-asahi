class AuxDiagnostic(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(); self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name); self.output = self.root / 'public'; self.output.mkdir()
        self.cache = self.root / 'aux-cache'; self.cache.write_bytes(b'raw-aux-A'); self.cache.chmod(0o600)
        for name, value in (('LD_AUX_INPUT', self.cache), ('LD_AUX_OUTPUT', self.output)):
            patched = patch.object(audio, name, value); patched.start(); self.addCleanup(patched.stop)
        printed = patch('builtins.print'); printed.start(); self.addCleanup(printed.stop)

    def state(self):
        state = ld_fixture(); state['caches'][audio.LD_AUX_NAME] = audio.ld_node(self.cache)
        return state

    def metadata(self, label):
        return json.loads((self.output / ('audio-aux-' + label + '.json')).read_text())

    def test_b0_b1_raw_join_capture_precedes_unchanged_refusal(self):
        before = self.state()
        with patch.object(audio, 'ld_state', return_value=before):
            self.assertIs(audio.ld_checkpoint(None, [], self.root, 'B0-587'), before)
        self.cache.write_bytes(b'raw-aux-B'); after = self.state()
        with patch.object(audio, 'ld_state', return_value=after):
            with self.assertRaisesRegex(ValueError, 'AUDIO_LDCONFIG_UNACCEPTED B1-593 aux-cache-byte-change'):
                audio.ld_checkpoint(None, [], self.root, 'B1-593', before)
        for label, data, state in [('B0-587', b'raw-aux-A', before), ('B1-593', b'raw-aux-B', after)]:
            path = self.output / ('audio-aux-' + label + '.bin'); row = self.metadata(label)
            self.assertEqual(path.read_bytes(), data); self.assertEqual(path.stat().st_mode & 0o777, 0o600)
            self.assertEqual(row['status'], 'CAPTURED'); self.assertEqual(row['node'], state['caches'][audio.LD_AUX_NAME])
            self.assertEqual(row['read_identity'][6], len(data))
        self.assertEqual(self.cache.read_bytes(), b'raw-aux-B')
        audio.ld_aux_diagnostic('B2-592', after)
        self.assertEqual(len(list(self.output.iterdir())), 4)

    def test_failed_read_is_explicit_and_cannot_waive_aux_refusal(self):
        before = self.state(); self.cache.write_bytes(b'raw-aux-B'); after = self.state()
        real_open = os.open
        def refuse(path, *args, **kwargs):
            if path == self.cache: raise PermissionError('private error text must not escape')
            return real_open(path, *args, **kwargs)
        with patch.object(audio.os, 'open', side_effect=refuse), patch.object(audio, 'ld_state', return_value=after):
            with self.assertRaisesRegex(ValueError, 'aux-cache-byte-change'):
                audio.ld_checkpoint(None, [], self.root, 'B1-593', before)
        row = self.metadata('B1-593')
        self.assertEqual((row['status'], row['reason']), ('UNAVAILABLE', 'PermissionError'))
        self.assertNotIn('private error', json.dumps(row)); self.assertFalse(list(self.output.glob('*.bin')))
        self.assertEqual(self.cache.read_bytes(), b'raw-aux-B')

    def test_read_identity_drift_does_not_publish_raw_bytes(self):
        state = self.state(); before = self.cache.stat()
        fields = ('st_dev', 'st_ino', 'st_mode', 'st_nlink', 'st_uid', 'st_gid', 'st_size', 'st_ctime_ns', 'st_mtime_ns')
        changed = SimpleNamespace(**{name: getattr(before, name) for name in fields}); changed.st_ctime_ns += 1
        with patch.object(audio.os, 'fstat', side_effect=[before, changed]):
            audio.ld_aux_diagnostic('B0-587', state)
        row = self.metadata('B0-587')
        self.assertEqual((row['status'], row['reason']), ('UNAVAILABLE', 'aux-diagnostic-read-drift'))
        self.assertFalse(list(self.output.glob('*.bin')))


class Audio(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(); self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.rows = json.loads((HERE / 'audio-inputs.json').read_text())
        self.before = container.lock((ROOT / 'scripts/ci/full-development-composition/expected-installed.lock').read_text())
        (self.root / 'expected-audio.lock').write_bytes((HERE / 'expected-audio.lock').read_bytes())

    def report(self, row):
        members = {p.removeprefix('/'): {'type': '0', 'mode': 0o644, 'uid': 0, 'gid': 0, 'sha256': '0' * 64}
                   for p in ('.PKGINFO', '.BUILDINFO', '.MTREE')}
        members.update({p: {'type': '5', 'mode': 0o755, 'uid': 0, 'gid': 0} for p in row['directories']})
        members.update({p['path'].removeprefix('/'): {'type': '0', 'mode': p['mode'], 'uid': 0, 'gid': 0, 'sha256': p['sha256']} for p in row['payload']})
        return {'sha256': row['sha256'], 'metadata': {'.PKGINFO': copy.deepcopy(row['metadata'])},
                'members': members, 'errors': row['generic_errors'][:], 'elf': {p: {'errors': []} for p in row['elf_paths']}}

    def test_exact_six_inventory_and_upstream_signature_selection(self):
        self.assertEqual(api.sha(HERE / 'audio-inputs.json'), inputs.POLICY)
        self.assertEqual(api.sha(HERE / 'expected-audio.lock'), audio.EXPECTED)
        self.assertEqual(len(audio.expected_inventory(self.root, self.before, self.rows, container)), 593)
        self.assertEqual({r['name'] for r in self.rows if r['origin'] == 'ALARM'}, {'lsp-plugins-lv2'})
        self.assertEqual(sum(len(r['metadata'].get('depend', [])) for r in self.rows), 22)
        self.assertEqual([len(r['generic_errors']) for r in self.rows], [10, 54, 5, 0, 0, 0])
        bad = dict(self.before); bad['bash'] = '99-1'
        with self.assertRaisesRegex(ValueError, 'checkpoint'): audio.expected_inventory(self.root, bad, self.rows, container)
        (self.root / 'expected-audio.lock').write_text((HERE / 'expected-audio.lock').read_text().replace('bash ', 'unexpected-bash '))
        with self.assertRaisesRegex(ValueError, 'inventory pin'): audio.expected_inventory(self.root, self.before, self.rows, container)

    def test_exact_payloads_and_closed_generic_errors(self):
        for row in self.rows:
            report = self.report(row)
            self.assertEqual(inputs.inspect(row, report, api)['depends'], row['metadata'].get('depend', []))
        row = self.rows[0]
        for mutate in (lambda r: r['errors'].append('unrelated failure'), lambda r: r['errors'].pop(),
                       lambda r: r.update(sha256='0' * 64),
                       lambda r: r['metadata']['.PKGINFO'].update(depend=[]),
                       lambda r: r['members'].update({'.INSTALL': {'type': '0'}}),
                       lambda r: r['members'][row['payload'][0]['path'].removeprefix('/')].update(sha256='0' * 64),
                       lambda r: r['members'][row['payload'][0]['path'].removeprefix('/')].update(mode=0o755),
                       lambda r: r['members'][row['payload'][0]['path'].removeprefix('/')].update(uid=1000)):
            report = self.report(row); mutate(report)
            with self.subTest(mutation=mutate), self.assertRaises((AssertionError, KeyError)):
                inputs.inspect(row, report, api)
        row = self.rows[2]; report = self.report(row)
        report['elf'][row['elf_paths'][0]]['errors'] = ['bad AArch64 layout']
        with self.assertRaisesRegex(AssertionError, 'ELF'): inputs.inspect(row, report, api)

    def simulate(self, drift=None, signature_failure=False):
        state = dict(self.before); events = []
