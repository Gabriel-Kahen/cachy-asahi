def readonly_test():
    rows=[]
    for path in (Path('/stage0'),WORK/'stage0'):
        target=path/'qualification-write-refusal'
        try:
            fd=os.open(target,os.O_CREAT|os.O_EXCL|os.O_WRONLY,0o600)
        except OSError as error:need(error.errno==30,'actual EROFS required, not another failure');rows.append(dict(path=str(path),errno=error.errno,denied=True))
        else:
            os.close(fd);target.unlink();raise ValueError('stage0 alias unexpectedly writable')
    return dict(paths=['/stage0','/work/build/stage0'],readonly=True,namespace_permissions_verified=True,write_attempts_denied=True,alias_write_attempts_denied=True,attempts=rows)


