def kernel(phase):
    data=dict(line.split(':',1) for line in Path('/proc/self/status').read_text().splitlines()if ':'in line)
    need(os.uname().machine=='aarch64' and data['Uid'].split()==data['Gid'].split()==['1001']*4,'actual native1001 qualification')
    need(all(int(data[k].strip(),16)==0 for k in ('CapPrm','CapEff','CapBnd','CapInh','CapAmb')) and data['NoNewPrivs'].strip()=='1','qualification cap0/NNP')
    limits={k:Path('/sys/fs/cgroup',k).read_text().strip() for k in ('cpu.max','memory.max','memory.swap.max','pids.max')}
    need(limits=={'cpu.max':'200000 100000','memory.max':'8589934592','memory.swap.max':'0','pids.max':'512'},'actual bounded qualification cgroup')
    need(set(p.name for p in Path('/sys/class/net').iterdir())=={'lo'} and os.statvfs('/').f_flag&os.ST_RDONLY,'offline readonly qualified image')
    need(all(os.statvfs(path).f_flag&os.ST_RDONLY for path in (ROOT,Path('/inputs'),Path('/materials'))),'actual readonly Source/qualification/material inputs')
    need(LLVM.is_dir() and not any(p.is_symlink() for p in (LLVM,*LLVM.parents)) and os.statvfs(LLVM).f_flag&os.ST_RDONLY,'real normal-installed readonly LLVM prefix')
    if phase=='probe':
        one,two=Path('/stage0'),WORK/'stage0';a,b=one.stat(),two.stat()
        need((a.st_dev,a.st_ino)==(b.st_dev,b.st_ino) and all(os.statvfs(p).f_flag&os.ST_RDONLY for p in (one,two)),'same stage0 tree both aliases read-only')


