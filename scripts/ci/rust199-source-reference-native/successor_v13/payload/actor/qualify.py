def need(value,why):
    if not value:raise ValueError(why)


def encode(value):return(json.dumps(value,sort_keys=True,indent=2,allow_nan=False)+'\n').encode()
def sha(path):
    with Path(path).open('rb') as stream:return hashlib.file_digest(stream,'sha256').hexdigest()
def read(path,cap=4*1024**2):
    path=Path(path);need(path.is_absolute() and all(not p.is_symlink() for p in (path,*path.parents)),'ordinary qualification input')
    fd=os.open(path,os.O_RDONLY|os.O_NONBLOCK|os.O_NOFOLLOW|os.O_CLOEXEC)
    try:
        before=os.fstat(fd);need(stat.S_ISREG(before.st_mode) and before.st_nlink==1 and 0<=before.st_size<=cap,'finite single-link qualification input')
        raw=b''
        while chunk:=os.read(fd,min(65536,cap+1-len(raw))):raw+=chunk;need(len(raw)<=cap,'qualification DATA cap')
        key=lambda s:(s.st_dev,s.st_ino,s.st_mode,s.st_nlink,s.st_size,s.st_mtime_ns,s.st_ctime_ns)
        need(len(raw)==before.st_size and key(before)==key(os.fstat(fd))==key(path.lstat()),'qualification input changed');return raw
    finally:os.close(fd)


