    need(phase in ('data','probe'),'two fixed qualification phases');p,c,m=plan()
    mount=load('qualification_kernel_mount_proof',ROOT/'actor/mount_proof.py')
    mount_phase='qualification-'+phase;mount_context=dict(source=p['provider']['source'],dispatch_sha256=p['provider']['dispatch_sha256'],input_admission_sha256=os.environ['QUALIFICATION_SHA256'],image_id=p['image_id'],volume_token=p['volume_owner']['token'],phase=mount_phase)
